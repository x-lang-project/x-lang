use super::{Detector, Spec};

pub(super) const SPECS: &[Spec] = &[
    Spec {
        identifier: "blocking-in-async",
        pattern: Detector::Tokens(
            "async(?:fn|\\{)[\\s\\S]*?(?:std::thread::sleep|std::fs::\\w+|\\.lock\\()",
        ),
        title: "Blocking call within async execution",
        description: "Blocking API-shaped syntax after an async body starts; lexical execution context requires review",
        positive: "async fn f() { std::thread::sleep(delay); }",
        negative: "async fn f() { tokio::time::sleep(delay).await; }",
    },
    Spec {
        identifier: "box-small-copy",
        pattern: Detector::Tokens("Box::new\\((?:true|false|[0-9]+(?:u\\d+|i\\d+)?)\\)"),
        title: "Heap allocation for small Copy value",
        description: "Box allocated for fixed-size cheap scalar or small Copy struct",
        positive: "fn f() { let x = Box::new(1u32); }",
        negative: "fn f() { let x = Box::new(value); }",
    },
    Spec {
        identifier: "buffered-write-flush-policy",
        pattern: Detector::Ast,
        title: "Buffered writer dropped without observable flush handling",
        description: "BufWriter construction and write-shaped call in a block without explicit flush",
        positive: "fn f() { let mut w = BufWriter::new(file); w.write_all(data); }",
        negative: "fn f() { let mut w = BufWriter::new(file); w.flush(); }",
    },
    Spec {
        identifier: "clone-before-borrow",
        pattern: Detector::Tokens("&[A-Za-z_]\\w*\\.(?:clone|to_owned)\\(\\)"),
        title: "Clone immediately borrowed",
        description: "A clone or to_owned result immediately passed by reference",
        positive: "fn f() { take(&value.clone()); }",
        negative: "fn f() { take(&value); }",
    },
    Spec {
        identifier: "clone-before-move",
        pattern: Detector::Ast,
        title: "Clone before last use",
        description: "Local cloned at its final lexical occurrence; move legality is not proven",
        positive: "fn f() { let value = input; consume(value.clone()); }",
        negative: "fn f() { let value = input; consume(value.clone()); consume(value); }",
    },
    Spec {
        identifier: "clone-copy-type",
        pattern: Detector::Tokens(
            "let([A-Za-z_]\\w*):(?:u\\d+|i\\d+|bool|char|f\\d+)=[^;]+;[^{}]*?\\1\\.clone\\(",
        ),
        title: "Clone on Copy value",
        description: "Clone call on a locally annotated built-in scalar type",
        positive: "fn f() { let value: u32 = 2; value.clone(); }",
        negative: "fn f() { let value: String = input; value.clone(); }",
    },
    Spec {
        identifier: "clone-in-loop",
        pattern: Detector::Tokens("(?:for[^{}]+|while[^{}]+|loop)\\{[^{}]*?\\.clone\\("),
        title: "Repeated cloning inside loops",
        description: "Clone method inside a simple loop body; invariance and cost are unresolved",
        positive: "fn f() { for item in items { value.clone(); } }",
        negative: "fn f() { let copy = value.clone(); for item in items { consume(&copy); } }",
    },
    Spec {
        identifier: "collect-length-only",
        pattern: Detector::Ast,
        title: "Collection used only for length",
        description: "Explicit Vec collection is immediately queried for length",
        positive: "fn f() { values.collect::<Vec<_>>().len(); }",
        negative: "fn f() { values.count(); }",
    },
    Spec {
        identifier: "collect-membership-only",
        pattern: Detector::Tokens("\\.collect(?:::[^;()]*)?\\(\\)\\.contains\\("),
        title: "Collection used only for membership",
        description: "Direct collect().contains() chain materialises a collection for membership",
        positive: "fn f() { values.collect::<Vec<_>>().contains(&value); }",
        negative: "fn f() { values.any(|value| value == target); }",
    },
    Spec {
        identifier: "collect-reiterate",
        pattern: Detector::Tokens("\\.collect(?:::[^;()]*)?\\(\\)\\.(?:into_iter|iter)\\("),
        title: "Intermediate collection immediately iterated",
        description: "Direct collect().iter()/into_iter() chain materialises an intermediate collection",
        positive: "fn f() { values.collect::<Vec<_>>().into_iter(); }",
        negative: "fn f() { values.into_iter(); }",
    },
    Spec {
        identifier: "eager-default",
        pattern: Detector::Tokens(
            "\\.(?:unwrap_or|or_insert|map_or)\\([A-Za-z_]\\w*(?:::\\w+)*\\(",
        ),
        title: "Eager expensive fallback",
        description: "unwrap_or or or_insert evaluates allocating/computing fallback eagerly",
        positive: "fn f() { value.unwrap_or(make_default()); }",
        negative: "fn f() { value.unwrap_or_else(make_default); }",
    },
    Spec {
        identifier: "empty-range-off-by-one",
        pattern: Detector::Tokens(
            "(?:0\\.\\.[A-Za-z_]\\w*\\.len\\(\\)-1|0\\.\\.=\\w+\\.len\\(\\))",
        ),
        title: "Suspicious range boundaries",
        description: "len - 1 or <= len patterns near indexing and iteration",
        positive: "fn f() { for i in 0..values.len()-1 { use_value(i); } }",
        negative: "fn f() { for i in 0..values.len() { use_value(i); } }",
    },
    Spec {
        identifier: "error-stringification",
        pattern: Detector::Tokens("\\.map_err\\(\\|\\w+\\|\\w+\\.to_string\\(\\)\\)"),
        title: "Structured error converted to string",
        description: "map_err/to_string discards typed error and source chain",
        positive: "fn f() { result.map_err(|error| error.to_string()); }",
        negative: "fn f() { result.map_err(Error::Source); }",
    },
    Spec {
        identifier: "error-to-default",
        pattern: Detector::Tokens(
            "\\.unwrap_or(?:_default\\(\\)|\\((?:0|false|String::new\\(\\)|Vec::new\\(\\))\\))",
        ),
        title: "Error replaced with normal-looking default",
        description: "Fallible operation mapped into empty/zero/default success-like value",
        positive: "fn f() { result.unwrap_or_default(); }",
        negative: "fn f() -> Result<(), Error> { result?; Ok(()) }",
    },
    Spec {
        identifier: "ffi-ownership-pairing",
        pattern: Detector::Tokens("(?:Box|CString|Arc|Rc)::from_raw\\("),
        title: "FFI allocation/deallocation pairing review",
        description: "Box/CString/Arc/Rc from_raw call requires ownership-pairing review",
        positive: "fn f() { let owned = unsafe { Box::from_raw(pointer) }; }",
        negative: "fn f() { let owned = Box::new(value); }",
    },
    Spec {
        identifier: "float-equality",
        pattern: Detector::Tokens("let(\\w+):f(?:32|64)=[^;]+;[^{}]*?\\1(?:==|!=)"),
        title: "Exact floating-point equality",
        description: "Locally annotated f32/f64 binding later compared with equality",
        positive: "fn f() { let value: f64 = 1.0; if value == target {} }",
        negative: "fn f() { let value: u32 = 1; if value == target {} }",
    },
    Spec {
        identifier: "format-then-append",
        pattern: Detector::Tokens("\\.push_str\\(&format!\\("),
        title: "Temporary formatted string appended",
        description: "push_str with format result, or string += formatted temporary",
        positive: "fn f() { text.push_str(&format!(\"{}\",value)); }",
        negative: "fn f() { write!(text,\"{}\",value); }",
    },
    Spec {
        identifier: "full-count-for-existence",
        pattern: Detector::Tokens("\\.count\\(\\)(?:>|!=|==)0"),
        title: "Full traversal for existence",
        description: "Iterator count compared to zero or collected len checked for emptiness",
        positive: "fn f() { if values.count() > 0 {} }",
        negative: "fn f() { if values.next().is_some() {} }",
    },
    Spec {
        identifier: "ignored-result-operation",
        pattern: Detector::Tokens(
            "(?:let_=|drop\\()[^;]*(?:\\.write(?:_all)?\\(|\\.flush\\(|\\.wait\\(|std::fs::\\w+\\()",
        ),
        title: "Fallible operation explicitly ignored",
        description: "let _ or drop used with I/O/process/synchronization Result",
        positive: "fn f() { let _ = file.write_all(data); }",
        negative: "fn f() -> Result<(), Error> { file.write_all(data)?; Ok(()) }",
    },
    Spec {
        identifier: "index-range-loop",
        pattern: Detector::Tokens("for(\\w+)in0\\.\\.(\\w+)\\.len\\(\\)\\{[^{}]*?\\2\\[\\1\\]"),
        title: "Range used solely for indexing",
        description: "for 0..collection.len where index only accesses that collection",
        positive: "fn f() { for index in 0..values.len() { consume(values[index]); } }",
        negative: "fn f() { for value in values { consume(value); } }",
    },
];
