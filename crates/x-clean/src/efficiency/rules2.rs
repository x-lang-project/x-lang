use super::{Detector, Spec};

pub(super) const SPECS: &[Spec] = &[
    Spec {
        identifier: "unchecked-narrowing-cast",
        pattern: Detector::Tokens(
            "let(\\w+):(?:u64|u128|i64|i128|usize|isize)=[^;]+;[^{}]*?\\1as(?:u8|u16|u32|i8|i16|i32)",
        ),
        title: "Potentially lossy integer casts",
        description: "as converts wider/signed integer into narrower/unsigned destination",
        positive: "fn f() { let value: u64 = 5; let short = value as u8; }",
        negative: "fn f() { let value: u64 = 5; let short = u8::try_from(value); }",
    },
    Spec {
        identifier: "unnecessary-owned-input",
        pattern: Detector::Tokens(
            "fn\\w+\\((\\w+):(?:String|Vec<[^>]+>|PathBuf)\\)[^{]*\\{\\1\\.(?:len|is_empty|as_str)\\(\\)\\}",
        ),
        title: "Owned parameter used only by borrowing",
        description: "Single owned input consumed only by a direct length/emptiness/string-view tail query",
        positive: "fn f(value: String) -> usize { value.len() }",
        negative: "fn f(value: &str) -> usize { value.len() }",
    },
    Spec {
        identifier: "unsafe-missing-contract",
        pattern: Detector::Ast,
        title: "Unsafe operation with no nearby safety rationale",
        description: "unsafe block/function/impl lacks structured SAFETY comment or contract doc",
        positive: "fn f() { unsafe { operation(); } }",
        negative: "fn f() { // SAFETY: pointer is valid\n unsafe { operation(); } }",
    },
    Spec {
        identifier: "vec-growth-known-size",
        pattern: Detector::Tokens("letmut(\\w+)=Vec::new\\(\\);for[^{}]+\\{[^{}]*?\\1\\.push\\("),
        title: "Vector growth with known upper bound",
        description: "Empty vector populated by push inside a following simple loop",
        positive: "fn f() { let mut result = Vec::new(); for item in items { result.push(item); } }",
        negative: "fn f() { let mut result = Vec::with_capacity(items.len()); for item in items { result.push(item); } }",
    },
    Spec {
        identifier: "zero-length-index",
        pattern: Detector::Ast,
        title: "Index access without visible empty guard",
        description: "Direct index-zero access requiring emptiness review",
        positive: "fn f() { consume(values[0]); }",
        negative: "fn f() { consume(values.get(0)); }",
    },
    Spec {
        identifier: "efficiency-extra-clone-then-clone",
        pattern: Detector::Tokens("\\.clone\\(\\)\\.clone\\("),
        title: "Repeated cloning",
        description: "A clone result is cloned again.",
        positive: "fn f() { value.clone().clone(); }",
        negative: "fn f() { value.clone(); }",
    },
    Spec {
        identifier: "efficiency-extra-owned-then-owned",
        pattern: Detector::Tokens("\\.to_owned\\(\\)\\.to_owned\\("),
        title: "Repeated ownership conversion",
        description: "An owned value is converted to ownership again.",
        positive: "fn f() { value.to_owned().to_owned(); }",
        negative: "fn f() { value.to_owned(); }",
    },
    Spec {
        identifier: "efficiency-extra-string-then-bytes",
        pattern: Detector::Tokens("\\.to_string\\(\\)\\.into_bytes\\("),
        title: "String allocation before byte access",
        description: "A string is allocated before accessing its bytes.",
        positive: "fn f() { value.to_string().into_bytes(); }",
        negative: "fn f() { value.as_bytes(); }",
    },
    Spec {
        identifier: "efficiency-extra-collect-then-collect",
        pattern: Detector::Tokens("\\.collect(?:::[^;()]*)?\\(\\)\\.into_iter\\(\\)\\.collect"),
        title: "Repeated collection",
        description: "A collected result is collected again.",
        positive: "fn f() { values.collect::<Vec<_>>().into_iter().collect::<Vec<_>>(); }",
        negative: "fn f() { values.collect::<Vec<_>>(); }",
    },
    Spec {
        identifier: "efficiency-extra-filter-next",
        pattern: Detector::Tokens("\\.filter\\([^;]*\\)\\.next\\("),
        title: "Filtering before next",
        description: "A filtered iterator is read with next.",
        positive: "fn f() { values.filter(|x| predicate(x)).next(); }",
        negative: "fn f() { values.find(|x| predicate(x)); }",
    },
    Spec {
        identifier: "efficiency-extra-map-flatten",
        pattern: Detector::Tokens("\\.map\\([^;]*\\)\\.flatten\\("),
        title: "Mapping before flatten",
        description: "An iterator maps values before flattening them.",
        positive: "fn f() { values.map(|x| expand(x)).flatten(); }",
        negative: "fn f() { values.flat_map(|x| expand(x)); }",
    },
    Spec {
        identifier: "efficiency-extra-filter-map-identity",
        pattern: Detector::Tokens("\\.filter_map\\(\\|\\w+\\|\\w+\\)"),
        title: "Identity filter_map",
        description: "filter_map uses an identity function.",
        positive: "fn f() { values.filter_map(|item| item); }",
        negative: "fn f() { values.flatten(); }",
    },
    Spec {
        identifier: "efficiency-extra-map-identity",
        pattern: Detector::Tokens("\\.map\\(\\|(\\w+)\\|\\1\\)"),
        title: "Identity mapping",
        description: "map returns each input unchanged.",
        positive: "fn f() { values.map(|item| item); }",
        negative: "fn f() { values.map(|item| transform(item)); }",
    },
    Spec {
        identifier: "efficiency-extra-enumerate-discard-index",
        pattern: Detector::Tokens("\\.enumerate\\(\\)\\.map\\(\\|\\(_,?(\\w+)\\)\\|\\1\\)"),
        title: "Unused enumeration indices",
        description: "Enumeration indices are discarded.",
        positive: "fn f() { values.enumerate().map(|(_, item)| item); }",
        negative: "fn f() { values.enumerate().map(|(index,item)| (index,item)); }",
    },
    Spec {
        identifier: "efficiency-extra-reverse-sort",
        pattern: Detector::Tokens("\\.sort(?:_unstable)?\\(\\);\\w+\\.reverse\\("),
        title: "Reversing sorted results",
        description: "A sorted collection is reversed.",
        positive: "fn f() { values.sort(); values.reverse(); }",
        negative: "fn f() { values.sort_by(|a,b| b.cmp(a)); }",
    },
    Spec {
        identifier: "efficiency-extra-reverse-next",
        pattern: Detector::Tokens("\\.rev\\(\\)\\.next\\("),
        title: "Reversing before next",
        description: "An iterator is reversed before reading one element.",
        positive: "fn f() { values.rev().next(); }",
        negative: "fn f() { values.next_back(); }",
    },
];
