use super::{Detector, Spec};

pub(super) const SPECS: &[Spec] = &[
    Spec {
        identifier: "linear-membership-loop",
        pattern: Detector::Ast,
        title: "Repeated linear membership checks",
        description: "Contains on an explicitly Vec-shaped binding inside a loop; workload cost is unresolved",
        positive: "fn f() { let other = Vec::<i32>::new(); for item in values { other.contains(&item); } }",
        negative: "fn f() { let found = values.contains(&item); }",
    },
    Spec {
        identifier: "lock-held-await",
        pattern: Detector::Ast,
        title: "Synchronisation guard across await",
        description: "Lock/read/write-shaped local before await with no explicit drop in this block",
        positive: "async fn f() { let guard = mutex.lock().unwrap(); work().await; consume(guard); }",
        negative: "async fn f() { let guard = mutex.lock().unwrap(); drop(guard); work().await; }",
    },
    Spec {
        identifier: "nested-lock-order",
        pattern: Detector::Ast,
        title: "Inconsistent acquisition order",
        description: "Two lock identities acquired in opposing orders across call paths",
        positive: "fn f() { let a = first.lock(); let b = second.lock(); } fn g() { let b = second.lock(); let a = first.lock(); }",
        negative: "fn f() { let a = first.lock(); let b = second.lock(); } fn g() { let a = first.lock(); let b = second.lock(); }",
    },
    Spec {
        identifier: "non-atomic-file-replace",
        pattern: Detector::Tokens("(?:fs::write|File::create)\\("),
        title: "Direct overwrite of durable state",
        description: "fs::write or File::create call requires overwrite/atomicity policy review",
        positive: "fn f() { std::fs::write(path,data); }",
        negative: "fn f() { std::fs::rename(temp,path); }",
    },
    Spec {
        identifier: "raw-pointer-lifetime",
        pattern: Detector::Ast,
        title: "Raw pointer escapes owner lifetime",
        description: "Tail pointer method call on a local binding; owner lifetime requires review",
        positive: "fn f() -> *const u8 { let value = Vec::<u8>::new(); value.as_ptr() }",
        negative: "fn f() -> Vec<u8> { let value = Vec::<u8>::new(); value }",
    },
    Spec {
        identifier: "redundant-borrow-layers",
        pattern: Detector::Ast,
        title: "Unnecessary reference/deref chains",
        description: "Nested reference expressions such as &&value; expected reference depth requires review",
        positive: "fn f() { consume(&&value); }",
        negative: "fn f() { consume(&value); }",
    },
    Spec {
        identifier: "refcell-borrow-scope",
        pattern: Detector::Tokens(
            "let(\\w+)=\\w+\\.borrow(?:_mut)?\\(\\);[^{}]*?\\w+\\(\\);[^{}]*?\\1",
        ),
        title: "Dynamic borrow guard held across nested work",
        description: "Borrow-shaped local remains lexically referenced after a callback-shaped call",
        positive: "fn f() { let guard = cell.borrow_mut(); callback(); consume(guard); }",
        negative: "fn f() { let guard = cell.borrow_mut(); consume(guard); callback(); }",
    },
    Spec {
        identifier: "regex-in-loop",
        pattern: Detector::Ast,
        title: "Regex construction in loop",
        description: "Literal regex constructor inside an actual loop; invariant compilation may be cached",
        positive: "fn f() { for item in items { Regex::new(\"pattern\"); } }",
        negative: "fn f() { let regex = Regex::new(pattern); for item in items { regex.is_match(item); } }",
    },
    Spec {
        identifier: "regex-per-call-literal",
        pattern: Detector::Ast,
        title: "Repeated compilation of literal regex",
        description: "Regex constructor receives a literal in executable AST",
        positive: "fn f() { Regex::new(\"pattern\"); }",
        negative: "fn f() { Regex::new(pattern); }",
    },
    Spec {
        identifier: "repeated-string-rewrite",
        pattern: Detector::Tokens(
            "(?:for[^{}]+|while[^{}]+|loop)\\{[^{}]*?(\\w+)=\\1\\.(?:replace|replacen|to_lowercase|to_uppercase)\\(",
        ),
        title: "Full string rewritten repeatedly",
        description: "Loop repeatedly replaces, joins or rebuilds same String",
        positive: "fn f() { for item in items { text = text.replace(from,to); } }",
        negative: "fn f() { for item in items { other = text.replace(from,to); } }",
    },
    Spec {
        identifier: "saturating-range-hidden-error",
        pattern: Detector::Tokens(
            "(?:0\\.\\.[^;{}]*\\.(?:saturating|wrapping)_\\w+\\(|\\[[^\\]]*\\.(?:saturating|wrapping)_\\w+\\()",
        ),
        title: "Arithmetic wrap/saturation masks invalid bounds",
        description: "wrapping/saturating operation feeds range/index/allocation size",
        positive: "fn f() { for i in 0..size.saturating_sub(1) {} }",
        negative: "fn f() { for i in 0..size {} }",
    },
    Spec {
        identifier: "skip-error-filter",
        pattern: Detector::Tokens("\\.filter_map\\(\\|\\w+\\|\\w+\\.ok\\(\\)\\)"),
        title: "Errors discarded by filter_map(Result::ok)",
        description: "filter_map closure calls ok(), potentially dropping error information",
        positive: "fn f() { values.filter_map(|result| result.ok()); }",
        negative: "fn f() { values.collect::<Result<Vec<_>,_>>(); }",
    },
    Spec {
        identifier: "sort-for-extremum",
        pattern: Detector::Tokens("(\\w+)\\.sort(?:_unstable)?\\(\\);\\1\\.(?:first|last)\\("),
        title: "Sorting to obtain one minimum or maximum",
        description: "Sort followed only by first/last on local collection",
        positive: "fn f() { values.sort(); values.first(); }",
        negative: "fn f() { values.iter().min(); }",
    },
    Spec {
        identifier: "spawn-without-reap",
        pattern: Detector::Tokens("let_=[^;]*\\.spawn\\("),
        title: "Child process started without visible wait/reap",
        description: "Spawn-shaped operation assigned to a discard binding",
        positive: "fn f() { let _ = Command::new(program).spawn(); }",
        negative: "fn f() { let mut child = Command::new(program).spawn(); child.wait(); }",
    },
];
