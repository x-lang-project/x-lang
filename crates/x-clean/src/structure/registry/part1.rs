use crate::Rule;

pub(super) fn rules() -> Vec<Rule> {
    vec![
        Rule {
            identifier: "structure-parallel-collection-fields",
            title: "Parallel collection representation",
            description: "A struct holds multiple Vec/map fields keyed or indexed together.",
            analysis: "Rust syntax and lexical module graph",
            positive: "struct A {left:Vec<u8>,right:Vec<u8>}",
            negative: "struct A{values:Vec<u8>,count:usize}",
        },
        Rule {
            identifier: "structure-primitive-domain-field-clusters",
            title: "Domain information represented by many primitives",
            description: "Struct fields or APIs repeatedly use the same primitive tuple/schema for a domain concept.",
            analysis: "Rust syntax and lexical module graph",
            positive: "struct A {x:u8,y:u8,z:u8,w:u8}",
            negative: "struct A{x:u8,y:u8,z:u8}",
        },
        Rule {
            identifier: "structure-public-reexport-chain",
            title: "Long public re-export chains",
            description: "A public item passes through several pub use layers.",
            analysis: "Rust syntax and lexical module graph",
            positive: "mod a{pub use crate::b::Thing;} mod b{pub use crate::c::Thing;} mod c{pub use crate::d::Thing;} mod d{pub struct Thing;}",
            negative: "mod a{pub use crate::b::Thing;} mod b{pub use crate::c::Thing;} mod c{pub struct Thing;}",
        },
        Rule {
            identifier: "structure-same-enum-shape",
            title: "Repeated enum variant schemas",
            description: "Enums repeatedly contain the same variant names and payload types.",
            analysis: "Rust syntax and lexical module graph",
            positive: "enum A{One(u8),Two} enum B{One(u8),Two}",
            negative: "enum A{One(u8),Two} enum B{One(u16),Two}",
        },
        Rule {
            identifier: "structure-same-field-record-shape",
            title: "Repeated record field shapes",
            description: "Different structs carry matching field names and types.",
            analysis: "Rust syntax and lexical module graph",
            positive: "struct A{x:u8,y:u8} struct B{x:u8,y:u8}",
            negative: "struct A{x:u8,y:u8} struct B{x:u8,y:u16}",
        },
        Rule {
            identifier: "structure-single-item-wrapper-module",
            title: "Thin module indirection",
            description: "A module contains only one forwarding re-export or a tiny wrapper declaration.",
            analysis: "Rust syntax and lexical module graph",
            positive: "mod thin {pub type Number=u8;}",
            negative: "mod thin{pub type Number=u8;pub fn f(){}}",
        },
        Rule {
            identifier: "structure-split-import-source",
            title: "Scattered imports from one source",
            description: "Multiple use declarations import from the same resolved module.",
            analysis: "Rust syntax and lexical module graph",
            positive: "use std::fmt::Debug; use std::fmt::Display;",
            negative: "use std::fmt::{Debug,Display};",
        },
        Rule {
            identifier: "structure-test-assertion-absence",
            title: "Tests without visible verification",
            description: "A test body has no recognised assertion, expect-result predicate, or fallible return.",
            analysis: "Rust syntax and lexical module graph",
            positive: "#[test] fn nothing() {let value=1;}",
            negative: "#[test] fn check(){assert_eq!(1,1);}",
        },
        Rule {
            identifier: "structure-test-branch-coverage-shape",
            title: "Unasserted branches in test bodies",
            description: "Some test control-flow paths skip all visible checks.",
            analysis: "Rust syntax and lexical module graph",
            positive: "#[test] fn maybe() {if true {assert!(true);}}",
            negative: "#[test] fn check(){if true{assert_eq!(1,1);}else{assert_eq!(2,2);}}",
        },
        Rule {
            identifier: "structure-test-external-tool-assumption",
            title: "External tool assumptions in tests",
            description: "Tests invoke literal executables without visible availability checks.",
            analysis: "Rust syntax and lexical module graph",
            positive: "#[test] fn tool() {let _=std::process::Command::new(\"git\").status();}",
            negative: "#[test] fn check(){if std::path::Path::new(\"git\").exists(){let _=std::process::Command::new(\"git\").status();}}",
        },
        Rule {
            identifier: "structure-test-fixed-filesystem-path",
            title: "Tests reuse fixed temporary paths",
            description: "Multiple tests create/write the same literal filesystem location.",
            analysis: "Rust syntax and lexical module graph",
            positive: "#[test] fn a(){let _=std::fs::write(\"shared.tmp\",b\"a\");} #[test] fn b(){let _=std::fs::write(\"shared.tmp\",b\"b\");}",
            negative: "#[test] fn a(){let _=std::fs::write(\"a.tmp\",b\"x\");} #[test] fn b(){let _=std::fs::write(\"b.tmp\",b\"x\");}",
        },
        Rule {
            identifier: "structure-test-global-state-mutation",
            title: "Tests mutate process-global state",
            description: "Tests change environment/current directory/global mutable registries.",
            analysis: "Rust syntax and lexical module graph",
            positive: "#[test] fn state(){let _=std::env::set_current_dir(\".\");}",
            negative: "#[test] fn f(){let _=std::env::current_dir();}",
        },
        Rule {
            identifier: "structure-test-helper-placement",
            title: "Test helper boundary leakage",
            description: "Production modules contain helpers apparently used exclusively by tests.",
            analysis: "Rust syntax and lexical module graph",
            positive: "fn test_setup(){} #[test] fn check(){test_setup();}",
            negative: "fn test_setup(){} fn production(){test_setup();} #[test] fn check(){test_setup();}",
        },
        Rule {
            identifier: "structure-test-order-dependency-hint",
            title: "Test setup dependency hints",
            description: "Tests read shared artifacts/state that other tests write without local setup.",
            analysis: "Rust syntax and lexical module graph",
            positive: "#[test] fn producer(){let _=std::fs::write(\"shared.tmp\",b\"x\");} #[test] fn consumer(){let _=std::fs::read(\"shared.tmp\");}",
            negative: "#[test] fn f(){let _=std::fs::write(\"shared.tmp\",b\"x\");let _=std::fs::read(\"shared.tmp\");}",
        },
        Rule {
            identifier: "structure-test-sleep-synchronization",
            title: "Sleep-based test synchronisation",
            description: "Tests use fixed sleeps to wait for async/process/thread work.",
            analysis: "Rust syntax and lexical module graph",
            positive: "#[test] fn wait(){std::thread::sleep(std::time::Duration::from_millis(1));}",
            negative: "#[test] fn f(){let _=\"sleep(\";assert_eq!(1,1);}",
        },
        Rule {
            identifier: "structure-test-table-opportunity",
            title: "Repeated scenario setup shape",
            description: "Neighbouring tests repeat a setup/action/assert sequence with differing case values.",
            analysis: "Rust syntax and lexical module graph",
            positive: "#[test] fn a(){let x=1; let y=x+1; assert_eq!(y,2);} #[test] fn b(){let x=2; let y=x+1; assert_eq!(y,3);}",
            negative: "#[test] fn a(){let x=1;assert_eq!(x,1);} #[test] fn b(){let x=2;assert_ne!(x,1);}",
        },
        Rule {
            identifier: "structure-type-alias-chain",
            title: "Deep type alias chains",
            description: "Aliases depend on other aliases through several levels.",
            analysis: "Rust syntax and lexical module graph",
            positive: "type A=B; type B=C; type C=D; type D=u8;",
            negative: "type A=B;type B=C;type C=u8;",
        },
        Rule {
            identifier: "structure-type-impl-scattering",
            title: "Type implementation scattering",
            description: "A single type has inherent impl blocks spread across many files.",
            analysis: "Rust syntax and lexical module graph",
            positive: "struct A; mod one{impl super::A{fn one(){}}} mod two{impl super::A{fn two(){}}} mod three{impl super::A{fn three(){}}}",
            negative: "struct A;mod one{impl super::A{fn a(){}}} mod two{impl super::A{fn b(){}}}",
        },
    ]
}
